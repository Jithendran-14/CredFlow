-- Read-only reports. Connect as CF_ORCHESTRATION; no cross-schema reads.
-- :application_id / :marketplace_id: dashed UUID text or NULL (disable filter).
-- RAWTOHEX displays the stored UUID bytes; external IDs remain ordinary text.

-- 1. Workflow/status projection reconciliation.
SELECT RAWTOHEX(w.ID) AS APPLICATION_UUID_HEX,
       RAWTOHEX(w.MARKETPLACE_ID) AS MARKETPLACE_UUID_HEX,
       w.REVISION AS APPLICATION_REVISION, w.WORKFLOW_VERSION, w.STATUS,
       w.HEALTH AS PROCESSING_HEALTH, w.DETAIL AS REASON_CODE,
       w.LENDER_ID, w.PRODUCT_ID, RAWTOHEX(w.SUBMISSION_ID) AS SUBMISSION_UUID_HEX,
       w.CONSENT_GRANTED, w.DISPATCH_AUTHORIZED, w.REVISION_PENDING, w.UPDATED_AT
FROM CF_ORCHESTRATION.CF_WORKFLOW w
WHERE (:application_id IS NULL OR w.ID = HEXTORAW(REPLACE(:application_id, '-', '')))
  AND (:marketplace_id IS NULL OR w.MARKETPLACE_ID = HEXTORAW(REPLACE(:marketplace_id, '-', '')))
ORDER BY w.UPDATED_AT DESC;

-- 2. Each unresolved technical issue, without request/answer payloads or secrets.
SELECT RAWTOHEX(w.ID) AS APPLICATION_UUID_HEX, w.STATUS,
       w.HEALTH AS APPLICATION_HEALTH, issue.OPERATION, issue.ISSUE_HEALTH,
       issue.FAILURE_CODE, issue.APPLICATION_REVISION,
       issue.INFORMATION_REQUEST_ID, issue.OFFER_ID, issue.ACCEPTANCE_ID
FROM CF_ORCHESTRATION.CF_WORKFLOW w
CROSS APPLY JSON_TABLE(w.HEALTH_ISSUES_JSON, '$.*'
  COLUMNS (
    OPERATION VARCHAR2(40) PATH '$.operation',
    RESOLVED VARCHAR2(5) PATH '$.resolved',
    ISSUE_HEALTH VARCHAR2(40) PATH '$.processingHealth',
    FAILURE_CODE VARCHAR2(300) PATH '$.failureCode',
    APPLICATION_REVISION NUMBER PATH '$.applicationRevision',
    INFORMATION_REQUEST_ID VARCHAR2(36) PATH '$.informationRequestId',
    OFFER_ID VARCHAR2(36) PATH '$.offerId',
    ACCEPTANCE_ID VARCHAR2(36) PATH '$.acceptanceId'
  )) issue
WHERE issue.RESOLVED = 'false'
  AND (:application_id IS NULL OR w.ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY w.UPDATED_AT DESC;

-- 3. One selected submission and its independently tracked cancellation/offer acknowledgement.
SELECT RAWTOHEX(s.ID) AS SUBMISSION_UUID_HEX, RAWTOHEX(s.APPLICATION_ID) AS APPLICATION_UUID_HEX,
       s.LENDER_ID, s.PRODUCT_ID, s.REVISION, s.STATUS AS LENDER_STATUS,
       s.EXTERNAL_ID, s.CANCELLATION_ACKNOWLEDGEMENT,
       RAWTOHEX(o.ID) AS OFFER_UUID_HEX, o.STATUS AS OFFER_STATUS,
       o.AMOUNT, o.CURRENCY, o.FEES, o.RATE, o.TENURE, o.EXPIRES_AT,
       o.ACKNOWLEDGEMENT AS LENDER_ACCEPTANCE_ACK,
       RAWTOHEX(o.ACCEPTANCE_ID) AS ACCEPTANCE_UUID_HEX, o.ACCEPTED_AT
FROM CF_ORCHESTRATION.CF_SUBMISSION s
LEFT JOIN CF_ORCHESTRATION.CF_OFFER o ON o.SUBMISSION_ID = s.ID
WHERE (:application_id IS NULL OR s.APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY s.CREATED_AT DESC;

-- 4. Questions with answers recorded but lender acknowledgement pending.
SELECT RAWTOHEX(q.ID) AS INFORMATION_UUID_HEX, RAWTOHEX(q.APPLICATION_ID) AS APPLICATION_UUID_HEX,
       RAWTOHEX(q.SUBMISSION_ID) AS SUBMISSION_UUID_HEX, q.STATUS,
       q.VERSION, q.ACKNOWLEDGEMENT, q.CREATED_AT, q.ANSWERED_AT
FROM CF_ORCHESTRATION.CF_INFORMATION_REQUEST q
WHERE q.STATUS = 'OPEN'
  AND q.ANSWERS_JSON IS NOT NULL
  AND q.ACKNOWLEDGEMENT = 'PENDING'
  AND (:application_id IS NULL OR q.APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY q.CREATED_AT;

-- 5. Durable delivery backlog. KIND is JOB/INBOX/OUTBOX/DLT.
SELECT KIND, STATUS, COUNT(*) AS DELIVERY_COUNT,
       MIN(NEXT_ATTEMPT_AT) AS EARLIEST_ATTEMPT, MAX(ATTEMPTS) AS MAX_ATTEMPTS
FROM CF_ORCHESTRATION.CF_M3_DELIVERY
GROUP BY KIND, STATUS
ORDER BY KIND, STATUS;

-- 6. Safe replay investigation; replay through the authorised API, never SQL UPDATE.
SELECT DELIVERY_ID, KIND, RAWTOHEX(APPLICATION_ID) AS APPLICATION_UUID_HEX,
       TARGET_NAME, POSITION_NO, STATUS, ATTEMPTS, NEXT_ATTEMPT_AT, LEASE_UNTIL, LAST_ERROR
FROM CF_ORCHESTRATION.CF_M3_DELIVERY
WHERE STATUS = 'DEAD'
  AND (:application_id IS NULL OR APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY POSITION_NO;

-- 7. Local outcome counts for the demonstration; Audit history belongs to Member 2.
SELECT STATUS, HEALTH, COUNT(*) AS APPLICATION_COUNT
FROM CF_ORCHESTRATION.CF_WORKFLOW
GROUP BY STATUS, HEALTH
ORDER BY STATUS, HEALTH;
