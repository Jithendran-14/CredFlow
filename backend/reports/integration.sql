-- Read-only reports. Connect as CF_LENDER_INTEGRATION.
-- :application_id is dashed UUID text or NULL; :lender_id is the configured lender UUID text or NULL.

-- 1. Canonical-to-external mapping and cancellation reconciliation.
SELECT RAWTOHEX(d.SUBMISSION_ID) AS SUBMISSION_UUID_HEX,
       RAWTOHEX(d.APPLICATION_ID) AS APPLICATION_UUID_HEX,
       d.APPLICATION_REVISION, d.LENDER_ID, d.EXTERNAL_ID, d.STATUS,
       d.CANCELLATION_REQUESTED, d.CANCELLATION_ACKNOWLEDGED,
       d.CALLBACK_SEQUENCE, d.EVENT_VERSION, d.SUBMITTED_AT, d.LEASE_UNTIL
FROM CF_LENDER_INTEGRATION.CF_INT_DISPATCH d
WHERE (:application_id IS NULL OR d.APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
  AND (:lender_id IS NULL OR d.LENDER_ID = :lender_id)
ORDER BY d.SUBMITTED_AT DESC NULLS LAST;

-- 2. Pending/uncertain/dead command work, joined only inside the owning schema.
SELECT RAWTOHEX(t.TASK_ID) AS TASK_UUID_HEX,
       RAWTOHEX(t.SUBMISSION_ID) AS SUBMISSION_UUID_HEX,
       RAWTOHEX(d.APPLICATION_ID) AS APPLICATION_UUID_HEX,
       d.LENDER_ID, t.OPERATION, t.STATUS, t.ATTEMPTS, t.POSITION,
       t.NEXT_ATTEMPT_AT, t.FAILURE_CODE
FROM CF_LENDER_INTEGRATION.CF_INT_TASK t
JOIN CF_LENDER_INTEGRATION.CF_INT_DISPATCH d ON d.SUBMISSION_ID = t.SUBMISSION_ID
WHERE t.STATUS <> 'DONE'
  AND (:application_id IS NULL OR d.APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY t.POSITION;

-- 3. Callback sequence gaps/dead callbacks; never expose CALLBACK_JSON or ACTOR_JSON.
SELECT RAWTOHEX(c.EVENT_ID) AS CALLBACK_UUID_HEX,
       RAWTOHEX(c.SUBMISSION_ID) AS SUBMISSION_UUID_HEX,
       d.LENDER_ID, d.CALLBACK_SEQUENCE AS LAST_APPLIED_SEQUENCE,
       c.LENDER_SEQUENCE, c.STATUS, c.ATTEMPTS, c.RECEIVED_AT,
       c.NEXT_ATTEMPT_AT, c.CORRELATION_ID, c.FAILURE_CODE
FROM CF_LENDER_INTEGRATION.CF_INT_CALLBACK c
JOIN CF_LENDER_INTEGRATION.CF_INT_DISPATCH d ON d.SUBMISSION_ID = c.SUBMISSION_ID
WHERE c.STATUS <> 'APPLIED'
  AND (:application_id IS NULL OR d.APPLICATION_ID = HEXTORAW(REPLACE(:application_id, '-', '')))
ORDER BY c.SUBMISSION_ID, c.LENDER_SEQUENCE;

-- 4. Queue totals for operational evidence.
SELECT 'COMMAND' AS QUEUE_KIND, STATUS, COUNT(*) AS ROW_COUNT, MAX(ATTEMPTS) AS MAX_ATTEMPTS
FROM CF_LENDER_INTEGRATION.CF_INT_TASK
GROUP BY STATUS
UNION ALL
SELECT 'CALLBACK', STATUS, COUNT(*), MAX(ATTEMPTS)
FROM CF_LENDER_INTEGRATION.CF_INT_CALLBACK
GROUP BY STATUS
ORDER BY QUEUE_KIND, STATUS;

-- 5. Delivery/outbox/inbox backlog without CLOB payloads.
SELECT KIND, STATUS, COUNT(*) AS DELIVERY_COUNT, MIN(NEXT_ATTEMPT_AT) AS EARLIEST_ATTEMPT
FROM CF_LENDER_INTEGRATION.CF_M3_DELIVERY
GROUP BY KIND, STATUS
ORDER BY KIND, STATUS;

-- 6. Cancellation still awaiting a lender acknowledgement.
SELECT RAWTOHEX(SUBMISSION_ID) AS SUBMISSION_UUID_HEX,
       RAWTOHEX(APPLICATION_ID) AS APPLICATION_UUID_HEX,
       LENDER_ID, EXTERNAL_ID, STATUS, CANCELLATION_REQUESTED, CANCELLATION_ACKNOWLEDGED
FROM CF_LENDER_INTEGRATION.CF_INT_DISPATCH
WHERE CANCELLATION_REQUESTED = 1 AND CANCELLATION_ACKNOWLEDGED = 0;
